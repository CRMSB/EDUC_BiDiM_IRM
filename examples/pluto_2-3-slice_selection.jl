    linkxaxes!(ax_rf, ax_gz)
    xlims!(ax_rf, 0, 12)
    ylims!(ax_rf, -0.35, 1.25)
    ylims!(ax_gz, Gz_ref_amp - 0.3, Gz_amp + 0.4)

    # Baseline zero reference lines
    hlines!(ax_rf, [0.0], color = :gray70, linestyle = :dot)
