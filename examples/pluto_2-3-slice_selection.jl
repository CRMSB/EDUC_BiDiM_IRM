## RF pulse shape and apodization

RF pulse shape are finite in time, generally their duration  is on the order of the ms.

This can me modeled mathematically as an ideal $B_\text{1,ideal}$ envelope multiply by a rect function of the duration of the RF pulse ($T_\text{rf}$) :

