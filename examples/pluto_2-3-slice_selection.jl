    )
    hidexdecorations!(ax_rf, ticks = false, grid = false)

    # Subplot 2: Gz Gradient Channel
    ax_gz = Axis(
        fig[2, 1],
        xlabel = "Time (ms)",
        ylabel = "G_z Gradient",
        xticks = 0:2:12,
        yticks = ([Gz_ref_amp, 0.0, Gz_amp], ["-G_ref", "0", "G_z"])
    )

