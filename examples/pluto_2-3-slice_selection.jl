It is not possible to easily solve such equation. A possible alternative is to use the **Small Angle Excitation approximation**. 

This approximation suppose that that $M_z = M_0$. This modification only uncouples the previous ordinary differential equations and lead to a solution of the form :

Slice Profile = Through-plane de-phasing x Fourier transform of the pulse envelop function

You can find more information how to derive this approximation in the following youtube course from **Rad229** stanford course.
"""

